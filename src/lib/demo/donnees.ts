import type { CourrierResume } from "@/types/courrier";

/**
 * Jeu de courriers de demonstration.
 *
 * Reprend exactement les lignes des maquettes : c'est ce qui permet de
 * comparer l'ecran realise et l'ecran dessine. Ces donnees ne servent qu'a
 * VITE_MODE_DEMO ; elles disparaissent du bundle des que le drapeau est faux.
 */

export interface CourrierDemo extends CourrierResume {
  /** Sert l'onglet « Qui m'est affecte ». Le serveur reel le deduit de la session. */
  affecteAMoi: boolean;
}

const c = (
  numero: string,
  correspondant: string,
  objet: string,
  etape: CourrierResume["etape"],
  structuresCotees: string[],
  nature: string,
  ecoules: number,
  alloues: number,
  depassement: number,
  jour: string,
  priorite: CourrierResume["priorite"] = "NORMALE",
  affecteAMoi = false,
  confidentiel = false,
): CourrierDemo => {
  // L'echeance se deduit du jour d'arrivee et du delai alloue. Le vrai serveur
  // compte en jours ouvres ; la demonstration se contente de jours calendaires.
  const echeance = new Date(`${jour}T09:15:00`);
  echeance.setDate(echeance.getDate() + alloues);

  return {
    id: Number(numero.slice(-4)),
    numero,
    sens: "ARRIVEE",
    objet,
    correspondant,
    nature,
    dateReception: `${jour}T09:15:00`,
    etape,
    priorite,
    confidentiel,
    echeance: echeance.toISOString().slice(0, 10),
    delai: { joursEcoules: ecoules, joursAlloues: alloues, joursDepassement: depassement },
    structuresCotees,
    affecteAMoi,
  };
};

